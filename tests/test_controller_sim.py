def test_an_engine_error_ends_the_run_invalid_with_its_row_written():
    """An engine that dies mid-run (a vLLM core crash) used to raise out of run(): no row, and the queue counted a
    crash. Now the run ends invalid with the error recorded, even though the engine refuses every call after it
    (the shutdown's calls are best-effort once the run has failed: staff engineer's review, 2026-10-02)."""
    from halfwritten.engines.base import EngineError

    class Dying(FakeEngine):
        dead = False

        async def pause(self, *a, **kw):
            self.dead = True
            raise EngineError("engine core died")

        async def counters(self):
            if self.dead:
                raise EngineError("no engine")
            return await super().counters()

        async def close(self):
            if self.dead:
                raise EngineError("no engine")
            return await super().close()

    summary, controller, engine, _ = quick_sim("D", engine_cls=Dying)
    assert not summary.valid and summary.error == "EngineError: engine core died"
    assert engine.dead and summary.wall_s > 0
    refused = [e.split(":")[0] for e in summary.events["shutdown_errors"]]
    assert refused == ["preemptions", "engine.counters", "engine.close"]  # every engine call, none fatal


@pytest.mark.parametrize("regime", ["B", "C1", "D", "E"])
def test_a_sync_calls_the_engine_in_the_same_order_in_every_pausing_regime(regime):
    """The sync's phases (controller.py _sync): pause, the count read alongside the push, the weights verified,
    the count read again as it settles, resume; a refactor that reorders them would change what the labels mean."""

    class Recording(FakeEngine):
        calls: list = []

        async def pause(self, *a, **kw):
            self.calls.append("pause")
            return await super().pause(*a, **kw)

        async def counters(self):
            self.calls.append("counters")
            return await super().counters()

        async def weight_version(self):
            self.calls.append("weight_version")
            return await super().weight_version()

        async def resume(self):
            self.calls.append("resume")
            return await super().resume()

    Recording.calls = []
    summary, *_ = quick_sim(regime, engine_cls=Recording)
    assert summary.valid and len(summary.syncs) >= 3
    calls = Recording.calls
    syncs = [i for i, c in enumerate(calls) if c == "pause"]
    for a, b in zip(syncs, syncs[1:]):
        one = calls[a:b]
        assert one[0] == "pause" and "resume" in one
        resume = one.index("resume")
        assert one[1] == "counters" and one[2] == "weight_version", one[:4]  # read with the push, then verified
        assert "counters" in one[3:resume]  # the second read, as the count settles, before resume
        assert one[resume + 1:] == ["counters"] * len(one[resume + 1:])  # after resume: only the preemption scrape
