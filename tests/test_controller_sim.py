def test_a_continuation_aborted_again_before_scheduling_keeps_its_prefix():
    """External review F07: a C1 answer keeps its tokens across continuations, so "no tokens" must mean none from this
    request. A continuation that is aborted before vLLM schedules it ends silently with its prefix held, and is
    resubmitted again, not a failed run. Here every first continuation waits unscheduled until the next pause."""

    class _FirstContinuationsWait(FakeEngine):
        def _admit(self, compute: bool = True):
            held = [r for r in self._waiting if r.req.rid.endswith("+1")]
            for r in held:
                self._waiting.remove(r)
            try:
                return super()._admit(compute)
            finally:
                self._waiting.extend(held)

    summary, controller, engine, _ = quick_sim("C1", budget_s=20.0, silent_waiting_aborts=True,
                                               engine_cls=_FirstContinuationsWait)
    assert summary.valid, (summary.error, summary.violations)
    assert summary.events["finishless_aborts"] > 0
    assert ledger_matches_truth(controller, engine) == []


def test_a_continuation_queued_behind_a_pause_keeps_its_prefix():
    """A C1 continuation that reaches the engine while the next abort pause is in force is queued, not aborted: its
    stream does not end, so the sync must not wait for it (it holds earlier tokens, but none from this request), and
    its cut relabels the open segment at its prefix length. Here every first continuation arrives during a pause."""

    class _FirstContinuationsArriveInAPause(FakeEngine):
        async def generate(self, req):
            if req.rid.endswith("+1"):
                while self._state != "paused":
                    await asyncio.sleep(0.001)
            async for chunk in super().generate(req):
                yield chunk

    summary, controller, engine, _ = quick_sim("C1", budget_s=20.0, engine_cls=_FirstContinuationsArriveInAPause)
    assert summary.valid, (summary.error, summary.violations)
    assert summary.events["queued_at_abort"] > 0
    assert ledger_matches_truth(controller, engine) == []


