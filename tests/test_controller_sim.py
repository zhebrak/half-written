from tests.simutil import ledger_matches_truth, quick_sim

REGIMES = ["A", "B", "C1", "C2", "D", "E", "F", "B+lora", "D+lora", "E+lora"]


@pytest.mark.parametrize("delivery", ["immediate", "one_step_late"])
@pytest.mark.parametrize("regime", REGIMES)
def test_every_regime_is_valid_and_its_ledger_matches_the_truth(regime, delivery):
    summary, controller, engine, _ = quick_sim(regime, delivery=delivery)
    assert summary.error is None and summary.violations == [] and summary.valid
    assert summary.steps >= 5
    assert ledger_matches_truth(controller, engine) == []
    # old tokens that arrive between a pause's acknowledgement and the cut are counted (the ack lag), not forbidden:
    # with immediate delivery there are none; later deliveries have them, and the cut waited for every one
    assert summary.late_old_tokens == 0 if delivery == "immediate" else summary.late_old_tokens >= 0
    und = summary.metrics()["undelivered"]  # every token the engine generated before a keep pause arrived by the cut
    assert und["positive"] == 0 and (und["syncs"] > 0) == (controller.regime.pause is not None)


def test_held_outputs_mislabel_tokens_and_the_counts_show_it():
    """If vLLM delivered the last old-weights tokens only after resume (E1 broken), the controller would label them
    with the new version. Comparing against the truth (the GPU canary) catches it, and so does the engine's own count
    of generated tokens: more were generated by the push than had arrived by the cut."""
    summary, controller, engine, _ = quick_sim("D", delivery="held_until_resume")
    report = compare(controller.ledger, engine.truth)
    assert not report["ok"] and report["bad_tokens"] > 0
    assert any(offset and offset > 0 for offset in report["boundary_offsets"])  # the ledger cut early
    assert summary.metrics()["undelivered"]["positive"] > 0


