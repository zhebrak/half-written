def test_a_run_that_lost_its_snapshot_at_T_is_invalid():
    """The primary endpoint is the snapshot at T: a trainer that never wrote it, or reported it failed, voids the
    run."""
    from halfwritten.trainer.client import SimTrainer
    orig = SimTrainer.snapshot

    async def lossy(self, tag, version):
        if tag != "tend":
            await orig(self, tag, version)
    SimTrainer.snapshot = lossy
    try:
        summary, controller, *_ = quick_sim("D", budget_s=20.0, snapshot_every_s=5.0)
    finally:
        SimTrainer.snapshot = orig
    assert not summary.valid and any("I16" in v and "tend" in v for v in summary.violations)


