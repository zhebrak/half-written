@pytest.mark.parametrize("regime", ["D", "E"])
def test_a_backlogged_server_cannot_slip_old_tokens_past_resume(regime):
    """Two H100s at 256 streams: old outputs kept arriving after a fixed 50 ms window. Delivered late and in bursts,
    every token must still carry the version that computed it: the engine's count says when the last one is in."""
    from simutil import ledger_matches_truth
    summary, controller, engine, _ = quick_sim(regime, budget_s=40.0, B=8, G=8, M=16, K=2, max_num_seqs=256,
                                              delivery="bursty", push_s=0.03)
    assert summary.valid, summary.violations
    assert ledger_matches_truth(controller, engine) == []
    # old outputs kept arriving up to ~0.2 s after an acknowledgement; each sync records how late (the ack lag), and
    # the cut waited for every one of them (nothing the engine had generated was undelivered)
    lags = [s["ack_lag_s"] for s in summary.syncs]
    assert 0.1 < max(lags) < 0.3
    assert all(s["fence_s"] > 0 and s["undelivered"] == 0 for s in summary.syncs)
    assert summary.metrics()["ack_lag_s"]["p100"] == max(lags)


def test_canary_checker_flags_an_off_by_one_boundary():
    from bench.canary import compare
    from halfwritten.ledger import Ledger
    led = Ledger()
    led.open("s", 0)
    led.extend("s", 5)
    led.cut("s", 5, 1, "stale_kv")  # the ledger cut after 5 tokens ...
    led.extend("s", 5)
    led.close("s", "stop")
    truth = lambda sid, attempt: [(0, False)] * 4 + [(1, True)] * 6  # noqa: E731 ... the weights changed after 4
    report = compare(led, truth)
    assert not report["ok"] and report["bad_tokens"] == 1 and report["boundary_offsets"] == {-1: 1}


